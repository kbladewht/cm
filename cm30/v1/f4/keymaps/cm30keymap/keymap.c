// 获取当前活动层
static uint8_t get_active_layer(void) {
    layer_state_t state = layer_state | default_layer_state;
    return get_highest_layer(state);
}


// 渲染图层动画
static void render_luna(uint8_t col, uint8_t line) {

    current_layer = get_active_layer();

    oled_set_cursor(col, line);

    switch (current_layer) {

        case 0:
            oled_write_raw_P(layer0, ANIM_SIZE);
            break;

        case 1:
            oled_write_raw_P(layer1, ANIM_SIZE);
            break;

        case 2:
            oled_write_raw_P(layer2, ANIM_SIZE);
            break;

        case 3:
            oled_write_raw_P(layer3, ANIM_SIZE);
            break;

        default:
            oled_write_raw_P(layer0, ANIM_SIZE);
            break;
    }
}


// 刷新 OLED
static void refresh_oled_display(void) {

    oled_clear();

    render_luna(0, 0);
}


